export function enrichPost(post: Post): Post {
  return {
    ...post,
    author: users.find((user) => user.id === post.authorId),
    category: categories.find((category) => category.id === post.categoryId),
  };
}

export function getDashboardSnapshot(): DashboardSnapshot {
  const latestPosts = posts.slice(0, 5).map(enrichPost);
  const draftPosts = posts.filter((post) => post.status === "DRAFT").map(enrichPost);

  return {
    totals: {
      posts: posts.length,
      published: posts.filter((post) => post.status === "PUBLISHED").length,
      drafts: draftPosts.length,
      users: users.length,
      media: media.length,
      categories: categories.length,
    },
    latestPosts,
    draftPosts,
    categoryBreakdown: categories.map((category) => ({
      name: category.name,
      value: posts.filter((post) => post.categoryId === category.id).length,
    })),
  };
}
